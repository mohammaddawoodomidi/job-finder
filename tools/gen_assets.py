#!/usr/bin/env python3
"""Generates src/assets.rs (report CSS/JS) from the original job_finder.py."""
import importlib.util, os, sys, tempfile
os.environ.setdefault("JOBFINDER_HOME", tempfile.mkdtemp())
spec = importlib.util.spec_from_file_location("jf", sys.argv[1]); jf = importlib.util.module_from_spec(spec); sys.modules["jf"] = jf; spec.loader.exec_module(jf)
def lit(s):
    for n in range(0, 8):
        d = "#" * n
        if '"' + d not in s: return 'r' + d + '"' + s + '"' + d
print("// @generated by tools/gen_assets.py from the original job_finder.py")
print("pub const REPORT_CSS: &str = " + lit(jf.REPORT_CSS) + ";")
print("pub const REPORT_JS: &str = " + lit(jf.REPORT_JS) + ";")
