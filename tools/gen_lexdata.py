#!/usr/bin/env python3
"""Generates src/lexdata.rs from the ORIGINAL job_finder.py so every keyword / pattern is copied exactly (no typos).
Usage: JOBFINDER_HOME=/tmp/jf python3 tools/gen_lexdata.py /path/to/job_finder.py > src/lexdata.rs"""
import importlib.util, os, sys, tempfile
os.environ.setdefault("JOBFINDER_HOME", tempfile.mkdtemp())
spec = importlib.util.spec_from_file_location("jf", sys.argv[1]); jf = importlib.util.module_from_spec(spec); sys.modules["jf"] = jf; spec.loader.exec_module(jf)

def lit(s):
    for n in range(0, 8):
        d = "#" * n
        if '"' + d not in s:
            return 'r' + d + '"' + s + '"' + d
    raise ValueError(s)

out = ["// @generated by tools/gen_lexdata.py from the original job_finder.py - do not edit by hand.", "#![allow(dead_code)]", ""]
def strs(name, items):
    out.append(f"pub const {name}: &[&str] = &[")
    for s in items: out.append("    " + lit(s) + ",")
    out.append("];\n")
def pairs(name, d):
    out.append(f"pub const {name}: &[(&str, &[&str])] = &[")
    for k, v in d.items(): out.append("    (" + lit(k) + ", &[" + ", ".join(lit(x) for x in v) + "]),")
    out.append("];\n")
def one(name, s): out.append(f"pub const {name}: &str = {lit(s)};\n")

strs("NONE_RAW", jf.NONE_RAW)
for n in ("ENTRY_EN","ENTRY_FA","ENTRY_TR","INTERN_EN","INTERN_FA","INTERN_TR","JUNIOR_EN","JUNIOR_FA","JUNIOR_TR",
          "EXCL_TITLE_EN","EXCL_TITLE_FA","EXCL_TITLE_TR","JOB_INTENT_EN","JOB_INTENT_FA","JOB_INTENT_TR"):
    strs(n, getattr(jf, n))
pairs("LANG_NAMES", jf.LANG_NAMES)
one("LANG_REQ_CUE", jf.LANG_REQ_CUE.pattern); one("LANG_OPT_CUE", jf.LANG_OPT_CUE.pattern)
one("LINK_BOOST_WORDS", jf.LINK_BOOST_WORDS.pattern)
strs("ATS_HOSTS", jf.ATS_HOSTS); strs("DENY_HOSTS", jf.DENY_HOSTS); strs("TRACKING_PARAMS", jf.TRACKING_PARAMS)
one("EXP_RANGE", jf._EXP_RANGE.pattern); one("EXP_SINGLE", jf._EXP_SINGLE.pattern)
one("EXP_CUE", jf._EXP_CUE.pattern); one("EXP_OPTIONAL", jf._EXP_OPTIONAL.pattern)
one("ARABIC_SCRIPT", jf._ARABIC_SCRIPT.pattern)
for n in ("_FA_ONLY","_PS_ONLY","_UR_ONLY","_KU_ONLY"): one(n.strip("_") + "_CHARS", "".join(sorted(getattr(jf, n))))
strs("AR_STOP", sorted(jf._AR_STOP)); strs("FA_STOP", sorted(jf._FA_STOP))
pairs("STOP", {k: sorted(v) for k, v in jf._STOP.items()})
pairs("PLACES", jf._PLACES)
strs("DUP_TITLE_NOISE", sorted(jf._DUP_TITLE_NOISE)); strs("DUP_COMPANY_NOISE", sorted(jf._DUP_COMPANY_NOISE))
one("REMOTE_YES", jf._REMOTE_YES.pattern); one("REMOTE_NO", jf._REMOTE_NO.pattern)
one("COMPANY_RE", jf._COMPANY_RE.pattern); one("LOC_RE", jf._LOC_RE.pattern)
one("NOT_APPLY", jf._NOT_APPLY.pattern); one("HANDLE_RE", jf._HANDLE_RE.pattern)
one("PHONE_CUE", jf._PHONE_CUE.pattern); one("PHONE_RE", jf._PHONE_RE.pattern)
one("EMAIL_RE", jf.EMAIL_RE.pattern); one("URL_RE", jf.URL_RE.pattern)
one("REL_RE", jf._REL_RE.pattern)
# the apply / join keyword lists are given to compile_keywords(); keep their final patterns
one("APPLY_STRONG", jf._APPLY_STRONG.pattern); one("APPLY_BROAD", jf._APPLY_BROAD.pattern); one("JOIN_NOISE", jf._JOIN_NOISE.pattern)
one("JOBLIKE", jf._JOBLIKE.pattern)
print("\n".join(out))
